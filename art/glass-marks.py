"""ArkadeOS Glass marks (Roland, 2026-11-14, round 6 approved: "na ez egész
jó lett"): the Start mark (the taskbar's menu button, the ArkadeOS logo) and
the Portal mark (the Portal app), drawn by glass_craft.

Each goes in its four hand-drawn optical sizes into marks/s (up to 32 px),
marks/m (33-63), marks/l (64-159) and marks/xl (160 and up) of both icon
themes: the light material in ArkadeOS Glass, the dark one in ArkadeOS Glass
Dark, so the mark reads on the light and the dark taskbar alike (the day/night
switch changes the theme). hicolor keeps the large dark mark for apps outside
our themes.

Names: arkadeos-launcher-glow (the taskbar's menu button, lit by its halo),
arkadeos-launcher and arkadeos-logo (the mark alone: About this System,
os-release), arkadeos-portal (the Portal).
Usage: glass-marks.py <icons folder>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glass_craft as K  # noqa: E402

out = sys.argv[1]
SIZES = {"s": "S", "m": "M", "l": "L", "xl": "XL"}
MARKS = {
    "arkadeos-launcher-glow": (K.start, True, "ArkadeOS"),
    "arkadeos-launcher": (K.start, False, "ArkadeOS"),
    "arkadeos-logo": (K.start, False, "ArkadeOS"),
    "arkadeos-portal": (K.portal, False, "ArkadeOS Portal"),
}
NOTE = "ArkadeOS Glass mark, generated by art/glass-marks.py (glass_craft): edit the generator, not this file."

for theme, mode in (("arkadeos-glass", "lt"), ("arkadeos-glass-dark", "dk")):
    for folder, size in SIZES.items():
        d = os.path.join(out, theme, "marks", folder)
        os.makedirs(d, exist_ok=True)
        for name, (draw, halo, label) in MARKS.items():
            open(os.path.join(d, name + ".svg"), "w").write(
                K.standalone(draw(size, halo), mode, label=label, comment=NOTE))

hicolor = os.path.join(out, "hicolor", "scalable", "apps")
os.makedirs(hicolor, exist_ok=True)
for name, (draw, halo, label) in MARKS.items():
    open(os.path.join(hicolor, name + ".svg"), "w").write(
        K.standalone(draw("XL", halo), "dk", size=256, label=label, comment=NOTE))
print(len(MARKS), "marks")
